// notices.mjs <site> <deny.toml> <LICENSES> <out>: the licences of the npm packages the page ships (PLAN.md M21.1;
// DEPENDENCIES.md T5). The page bundles from the lockfile's production tree only (every package not marked `dev`), so
// that tree is what this credits: each package's name, version, licence and licence text. A package that ships no
// licence text is credited with its author and the SPDX text in LICENSES/. A licence outside deny.toml's allow-list,
// or with no text either way, fails the build.
import { existsSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const [site, denyToml, licenses, out] = process.argv.slice(2);
if (!site || !denyToml || !licenses || !out) {
  console.error("usage: notices.mjs <site> <deny.toml> <LICENSES> <out>");
  process.exit(2);
}

const allowed = (() => {
  const section = readFileSync(denyToml, "utf8").split(/^\[licenses\]$/m)[1] ?? "";
  const list = /^allow = \[([^\]]*)\]/m.exec(section)?.[1] ?? "";
  return new Set([...list.matchAll(/"([^"]+)"/g)].map((m) => m[1]));
})();

// An SPDX expression passes if one alternative of an OR passes and every term of an AND does.
const passes = (expression) =>
  expression
    .replace(/[()]/g, "")
    .split(/\s+OR\s+/)
    .some((alternative) => alternative.split(/\s+AND\s+/).every((id) => allowed.has(id.trim())));

const lock = JSON.parse(readFileSync(join(site, "package-lock.json"), "utf8"));
const failures = [];
const sections = [];
for (const [path, entry] of Object.entries(lock.packages ?? {})) {
  if (path === "" || entry.dev) continue;
  const name = path.replace(/^.*node_modules\//, "");
  const dir = join(site, path);
  const manifest = JSON.parse(readFileSync(join(dir, "package.json"), "utf8"));
  const license = entry.license ?? manifest.license;
  if (typeof license !== "string" || !passes(license)) {
    failures.push(`${name}@${entry.version}: licence ${JSON.stringify(license)} is not in deny.toml's allow-list`);
    continue;
  }
  const file = readdirSync(dir).find((f) => /^(licen[cs]e|copying)/i.test(f));
  const spdx = join(licenses, `${license}.txt`);
  const author = typeof manifest.author === "string" ? manifest.author : manifest.author?.name;
  let text;
  if (file) text = readFileSync(join(dir, file), "utf8").trim();
  else if (existsSync(spdx) && author)
    text = `The package ships no licence text. Copyright (c) ${author}, under:\n\n${readFileSync(spdx, "utf8").trim()}`;
  else {
    failures.push(`${name}@${entry.version}: no licence text, and no author with ${spdx}`);
    continue;
  }
  sections.push(`${name} ${entry.version} (${license})\n${"-".repeat(40)}\n\n${text}\n`);
}
if (failures.length > 0) {
  console.error(failures.join("\n"));
  process.exit(1);
}
const header =
  "Licences of the npm packages in this page\n" +
  "=========================================\n\n" +
  "Generated by scripts/site/notices.mjs from the site's lockfile (its production tree).\n\n";
writeFileSync(out, header + sections.join("\n"));
console.log(`notices: ${sections.length} npm packages credited`);
