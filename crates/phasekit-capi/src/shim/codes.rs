/// The v8.0.0 code of a parameter name: an output table name or its all-uppercase form, the first that matches.
pub fn parameter_code(name: &str) -> Option<i32> {
    PARAMETERS.iter().find(|(key, _)| spells(name, key)).map(|(_, code)| *code)
}

/// The v8.0.0 code of an input-pair name, exactly as written.
pub fn input_pair_code(name: &str) -> Option<i32> {
    PAIRS.iter().find(|(key, _)| *key == name).map(|(_, code)| *code)
}

/// The parameter names, in the table's order (compat's `output_names`).
pub fn parameter_names() -> impl Iterator<Item = &'static str> {
    PARAMETERS.iter().map(|(name, _)| *name)
}
