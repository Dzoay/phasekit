/// The bundle of φ at `rho` (kg/m³) and `t` (K): n₁ ln δ gives A00, A01 = n₁ and A02 = −n₁; each term n δ^I τ^J adds
/// itself times 1, I, I(I − 1), J, J(J − 1) and IJ to A00, A01, A02, A10, A20 and A11.
pub(super) fn evaluate(rho: f64, t: f64) -> Bundle {
    let (delta, tau) = (rho / RHO_C, T_C / t);
    let mut out = Bundle { a00: N1 * math::ln(delta), a10: 0.0, a01: N1, a20: 0.0, a11: 0.0, a02: -N1 };
    for &(i, j, n) in &TERMS {
        let term = n * math::powi(delta, i) * math::powi(tau, j);
        let (fi, fj) = (f64::from(i), f64::from(j));
        out.a00 += term;
        out.a01 += fi * term;
        out.a02 += fi * (fi - 1.0) * term;
        out.a10 += fj * term;
        out.a20 += fj * (fj - 1.0) * term;
        out.a11 += fi * fj * term;
    }
    out
}
